export function translate(lang, key, params) {
  let s = (dict[lang] && dict[lang][key]) || dict.en[key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split('{' + k + '}').join(String(v))
    }
  }
  return s
}
